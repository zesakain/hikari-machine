static int testDecodeFromFile() {
    const std::string tempFile = "/tmp/hikari_test_sample.bmp";
    auto bmpData = create2x2Bmp();
    {
        std::ofstream out(tempFile, std::ios::binary);
        out.write(reinterpret_cast<const char*>(bmpData.data()),
                  static_cast<std::streamsize>(bmpData.size()));
    }

    auto res = ImageDecoder::decodeFromFile(tempFile, 4, false);
    std::filesystem::remove(tempFile);

    TEST_CHECK(res.hasValue());
    const auto& img = res.value();
    TEST_CHECK(img.width == 2);
    TEST_CHECK(img.height == 2);
    TEST_CHECK(img.channels == 4);

    return 0;
}

static int testErrorHandling() {
    // 1. Non-existent file
    auto nonExistent = ImageDecoder::decodeFromFile("/non/existent/path/image.png");
    TEST_CHECK(!nonExistent.hasValue());
    TEST_CHECK(nonExistent.error().code == eng::ErrorCode::EntityNotFound);

    // 2. Empty memory buffer
    auto emptyBuffer = ImageDecoder::decodeFromMemory({});
    TEST_CHECK(!emptyBuffer.hasValue());
    TEST_CHECK(emptyBuffer.error().code == eng::ErrorCode::InvalidArgument);

    // 3. Corrupt buffer
    uint8_t garbage[] = {0xDE, 0xAD, 0xBE, 0xEF, 0x01, 0x02};
    auto corruptBuffer = ImageDecoder::decodeFromMemory(garbage);
    TEST_CHECK(!corruptBuffer.hasValue());
    TEST_CHECK(corruptBuffer.error().code == eng::ErrorCode::ResourceCreationFailed);

    return 0;
}

